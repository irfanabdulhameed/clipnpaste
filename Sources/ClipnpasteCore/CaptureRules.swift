import Foundation
import UniformTypeIdentifiers

/// Pasteboard type identifiers the reader looks at.
public enum PasteboardTypes {
    public static let transient = "org.nspasteboard.TransientType"
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// UTF-8 bundle id of the app that wrote the clipboard (nspasteboard.org).
    public static let source = "org.nspasteboard.source"
    /// Universal Clipboard content from another device.
    public static let remote = "com.apple.is-remote-clipboard"
    /// Older markers from password managers and text expanders.
    public static let legacy = [
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]
    public static let skipMarkers = [transient, concealed, autoGenerated] + legacy

    public static let fileURL = "public.file-url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let heic = "public.heic"
    public static let jpeg = "public.jpeg"
    /// Image data in priority order.
    public static let images = [png, tiff, heic, jpeg]
    public static let rtf = "public.rtf"
    public static let html = "public.html"
    public static let plainText = "public.utf8-plain-text"
}

/// Read access to a pasteboard, so the rules can run against a fake in tests.
@MainActor
public protocol PasteboardAccess: AnyObject {
    var changeCount: Int { get }
    /// Every type on the pasteboard, across all items.
    var types: Set<String> { get }
    func data(forType type: String) -> Data?
    func string(forType type: String) -> String?
    /// File URLs on the pasteboard, in order.
    func fileURLs() -> [URL]
}

public struct SourceApp: Sendable, Equatable {
    public var bundleID: String?
    public var name: String?

    public init(bundleID: String?, name: String?) {
        self.bundleID = bundleID
        self.name = name
    }
}

public enum CapturedContent: Sendable, Equatable {
    case text(String, rtf: Data?, html: Data?)
    /// Image bytes as found on the pasteboard, with their type.
    case imageData(Data, type: String)
    /// An image file copied in Finder.
    case imageFile(URL)
}

public enum SkipReason: Sendable, Equatable {
    case empty
    case marker(String)
    case ownWrite
    case ignoredApp(String)
    case notAnImage
    case tooLarge
    case blank
    case unsupported
}

public enum CaptureResult: Sendable, Equatable {
    case capture(CapturedContent, source: SourceApp?)
    case skip(SkipReason)
}

/// Decides what a copy is and whether to keep it, in the plan's strict order:
/// skip markers, ignored apps, image file, other file, plain text (with its rich versions), image data.
public struct CaptureRules: Sendable {
    /// Password managers whose copies are never kept, matched without case.
    public static let passwordManagers: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword4",
        "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.apple.keychainaccess",
        "com.apple.passwords",
        "in.sinew.enpass-desktop",
        "com.hicknhacksoftware.macpass",
    ]
    public static let maxTextBytes = 10 * 1024 * 1024
    public static let maxImageBytes = 50 * 1024 * 1024
    /// Rich versions larger than this are dropped; the plain text is still kept.
    public static let maxRichBytes = 10 * 1024 * 1024

    public var ignoredApps: Set<String>
    /// Our own bundle id; a copy tagged with it is our own write.
    public var ownBundleID: String?

    public init(
        ignoredApps: Set<String> = CaptureRules.passwordManagers,
        ownBundleID: String? = Bundle.main.bundleIdentifier
    ) {
        self.ignoredApps = Set(ignoredApps.map { $0.lowercased() })
        self.ownBundleID = ownBundleID
    }

    @MainActor
    public func read(_ pb: some PasteboardAccess, frontmost: SourceApp?) -> CaptureResult {
        let types = pb.types
        if types.isEmpty { return .skip(.empty) }
        if let marker = PasteboardTypes.skipMarkers.first(where: types.contains) { return .skip(.marker(marker)) }

        let source = sourceApp(pb, types: types, frontmost: frontmost)
        if let id = source?.bundleID?.lowercased() {
            if id == ownBundleID?.lowercased() { return .skip(.ownWrite) }
            if ignoredApps.contains(id) { return .skip(.ignoredApp(id)) }
        }

        // Finder puts the file's icon beside the URL as image data, so the URL wins.
        if types.contains(PasteboardTypes.fileURL), let url = pb.fileURLs().first {
            let values = try? url.resourceValues(forKeys: [.contentTypeKey, .fileSizeKey])
            let type = values?.contentType ?? UTType(filenameExtension: url.pathExtension)
            guard let type, type.conforms(to: .image) else { return .skip(.notAnImage) }
            if let size = values?.fileSize, size > Self.maxImageBytes { return .skip(.tooLarge) }
            return .capture(.imageFile(url), source: source)
        }

        // Plain text wins over a bundled picture (spreadsheets and slides put one beside the text),
        // unless the text is only the address of the image (browser "Copy Image").
        let plain = pb.string(forType: PasteboardTypes.plainText)
        let hasText = plain.map { !$0.allSatisfy(\.isWhitespace) } ?? false
        let textIsImageAddress = plain.map(Self.isSingleAddress) ?? false
        for type in PasteboardTypes.images where types.contains(type) && (!hasText || textIsImageAddress) {
            guard let data = pb.data(forType: type), !data.isEmpty else { continue }
            if data.count > Self.maxImageBytes { return .skip(.tooLarge) }
            return .capture(.imageData(data, type: type), source: source)
        }

        guard let text = plain else { return .skip(.unsupported) }
        if text.allSatisfy(\.isWhitespace) { return .skip(.blank) }
        if text.utf8.count > Self.maxTextBytes { return .skip(.tooLarge) }
        let rich = { (type: String) -> Data? in
            guard types.contains(type), let data = pb.data(forType: type), data.count <= Self.maxRichBytes else { return nil }
            return data
        }
        return .capture(.text(text, rtf: rich(PasteboardTypes.rtf), html: rich(PasteboardTypes.html)), source: source)
    }

    /// One URL or file path and nothing else.
    static func isSingleAddress(_ text: String) -> Bool {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if t.isEmpty || t.contains(where: \.isWhitespace) { return false }
        if t.hasPrefix("/") || t.hasPrefix("~/") { return true }
        guard let scheme = URL(string: t)?.scheme?.lowercased() else { return false }
        return ["http", "https", "file"].contains(scheme)
    }

    /// The source marker when present; otherwise the frontmost app, except for a
    /// Universal Clipboard copy, which no app on this Mac made.
    @MainActor
    private func sourceApp(_ pb: some PasteboardAccess, types: Set<String>, frontmost: SourceApp?) -> SourceApp? {
        if types.contains(PasteboardTypes.source),
           let id = pb.string(forType: PasteboardTypes.source), !id.isEmpty {
            let name = frontmost?.bundleID == id ? frontmost?.name : nil
            return SourceApp(bundleID: id, name: name)
        }
        if types.contains(PasteboardTypes.remote) { return nil }
        return frontmost
    }
}

/// Turns captured content into a clip. Images are written to disk (PNG and thumbnail)
/// before the clip is returned. Runs off the main actor.
enum ClipBuilder {
    struct Failed: Error {}

    static func make(_ content: CapturedContent, source: SourceApp?, date: Date, files: ClipFiles) throws -> Clip {
        switch content {
        case let .text(text, rtf, html):
            return Clip(
                kind: .text,
                plainText: text,
                rtfData: rtf,
                htmlData: html,
                sourceBundleID: source?.bundleID,
                sourceAppName: source?.name,
                createdAt: date,
                contentHash: ContentHash.of(text)
            )
        case let .imageData(data, type):
            return try image(data, isPNG: type == PasteboardTypes.png, source: source, date: date, files: files)
        case let .imageFile(url):
            guard ClipFiles.fileSize(url) <= CaptureRules.maxImageBytes else { throw Failed() }
            let data = try Data(contentsOf: url, options: .mappedIfSafe)
            let isPNG = UTType(filenameExtension: url.pathExtension)?.conforms(to: .png) ?? false
            return try image(data, isPNG: isPNG, source: source, date: date, files: files)
        }
    }

    private static func image(_ data: Data, isPNG: Bool, source: SourceApp?, date: Date, files: ClipFiles) throws -> Clip {
        guard let png = ImageCodec.normalizedPNG(data, isPNG: isPNG),
              let size = ImageCodec.pixelSize(of: png)
        else { throw Failed() }
        let hash = ContentHash.of(png)
        let imageURL = files.imageURL(hash: hash)
        let thumbURL = files.thumbnailURL(hash: hash)
        try files.createDirectories()
        let fm = FileManager.default
        if !fm.fileExists(atPath: imageURL.path) {
            try png.write(to: imageURL, options: .atomic)
        }
        if !fm.fileExists(atPath: thumbURL.path) {
            guard let thumb = Thumbnailer.thumbnailPNG(from: png) else { throw Failed() }
            try thumb.write(to: thumbURL, options: .atomic)
        }
        return Clip(
            kind: .image,
            imageURL: imageURL,
            thumbnailURL: thumbURL,
            pixelWidth: size.width,
            pixelHeight: size.height,
            characterCount: 0,
            sourceBundleID: source?.bundleID,
            sourceAppName: source?.name,
            createdAt: date,
            contentHash: hash
        )
    }
}
