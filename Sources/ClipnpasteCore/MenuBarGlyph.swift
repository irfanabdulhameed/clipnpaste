import AppKit

/// The menu bar icon. Drawn pixel by pixel at 1× and 2×, so every straight edge sits on a whole
/// pixel on the external 1× displays as well as on Retina. It is a template image: macOS tints it
/// for light, dark and tinted menu bars and for the highlighted state when the menu is open.
///
/// Three designs, all from the app's own world (compare them with scripts/menubar-options.swift):
///   1  Lift   a card tilting up off the stack, as in the app icon
///   2  Shelf  the glass panel at the bottom of the screen, holding a row of cards
///   3  Pick   one card inside the selection ring
public enum MenuBarGlyph {
    /// The design the menu bar shows. Change this one number to switch.
    public static let chosen = 1
    public static let names = [1: "Lift", 2: "Shelf", 3: "Pick"]
    /// The image size in points. Both even, so the status bar centres it on whole pixels.
    public static let width = 18
    public static let height = 16

    /// The status item image for `design`, with a 1× and a 2× bitmap.
    public static func image(_ design: Int = chosen) -> NSImage {
        let image = NSImage(size: NSSize(width: width, height: height))
        image.addRepresentation(bitmap(design, scale: 1))
        image.addRepresentation(bitmap(design, scale: 2))
        image.isTemplate = true
        image.accessibilityDescription = "Clipnpaste"
        return image
    }

    /// The pixel rows of `design` at `scale` (1 or 2), top to bottom: `.` clear, `#` solid, and
    /// `1`–`9` for 10–90 % (only on curves and the tilt at 2×; 1× is solid or clear).
    public static func rows(_ design: Int, scale: Int) -> [String] {
        switch (design, scale) {
        case (1, 1): lift1x
        case (1, _): lift2x
        case (2, 1): shelf1x
        case (2, _): shelf2x
        case (3, 1): pick1x
        default: pick2x
        }
    }

    /// Coverage of one pixel character, or nil if it is not one.
    public static func alpha(_ c: Character) -> Double? {
        switch c {
        case ".": 0
        case "#": 1
        case "1"..."9": Double(c.wholeNumberValue!) / 10
        default: nil
        }
    }

    static func bitmap(_ design: Int, scale: Int) -> NSBitmapImageRep {
        let rows = rows(design, scale: scale)
        let w = width * scale, h = height * scale
        let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: w, pixelsHigh: h, bitsPerSample: 8,
                                   samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                   colorSpaceName: .deviceRGB, bytesPerRow: w * 4, bitsPerPixel: 32)!
        let data = rep.bitmapData!
        data.initialize(repeating: 0, count: w * h * 4)
        // Black with the pixel's coverage as alpha (premultiplied, so the colour stays 0).
        for (y, row) in rows.prefix(h).enumerated() {
            for (x, c) in row.prefix(w).enumerated() {
                data[(y * w + x) * 4 + 3] = UInt8(((alpha(c) ?? 0) * 255).rounded())
            }
        }
        rep.size = NSSize(width: width, height: height)
        return rep
    }

